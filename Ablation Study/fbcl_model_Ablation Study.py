def choose_file(kind, uploaded_names):
    lower_names = [name.lower() for name in uploaded_names]
    if kind == "train":
        keywords = ["augmented", "train", "training", "preprocessed"]
    elif kind == "val":
        keywords = ["validation", "val"]
    elif kind == "test":
        keywords = ["test"]
    else:
        keywords = []
    candidates = [orig for orig, low in zip(uploaded_names, lower_names) if any(k in low for k in keywords)]
    if len(candidates) == 1:
        return candidates[0]
    raise FileNotFoundError(
        f"Could not automatically choose the {kind} file among: {uploaded_names}. "
        f"Rename your files to clearly contain 'train'/'validation'/'test'."
    )

