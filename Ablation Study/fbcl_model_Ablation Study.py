DEFAULT_CONFIG = {
    "name": "0_baseline_exact",
    "d_model": 256,
    "n_heads": 16,
    "n_layers": 6,
    "dropout": 0.15,
    "boosting_dropout": 0.12,
    "use_boosting_heads": True,
    "use_distillation": True,
    "use_batchnorm": True,
    "use_dropout": True,
    "use_weighted_sampler": True,
    "use_grad_clip": True,
    "use_lr_schedule": True,
    "lr": 3e-4,
    "weight_decay": 5e-5,
    "temperature": 2.5,
    "distillation_alpha": 0.8,
}


def norm_layer(cfg, dim):
    return nn.BatchNorm1d(dim) if cfg["use_batchnorm"] else nn.Identity()


def dropout_layer(cfg, p):
    return nn.Dropout(p if cfg["use_dropout"] else 0.0)


class ConfigurableFBCLTransformer(nn.Module):
    def __init__(self, cfg, n_features, n_classes):
        super().__init__()
        self.cfg = cfg
        self.n_features = n_features
        self.d_model = cfg["d_model"]
        self.n_classes = n_classes

        d_model = cfg["d_model"]

        self.feature_embedding = nn.Sequential(
            nn.Linear(1, d_model // 2),
            nn.GELU(),
            nn.Linear(d_model // 2, d_model)
        )

        self.pos_embedding = nn.Parameter(torch.randn(1, n_features, d_model) * 0.02)
        self.pos_scale = nn.Parameter(torch.ones(1))

        encoder_layer = nn.TransformerEncoderLayer(
            d_model=d_model,
            nhead=cfg["n_heads"],
            dim_feedforward=d_model * 4,
            dropout=cfg["dropout"] if cfg["use_dropout"] else 0.0,
            batch_first=True,
            activation='gelu',
            norm_first=True
        )
        self.transformer = nn.TransformerEncoder(encoder_layer, num_layers=cfg["n_layers"])
        self.layer_norm = nn.LayerNorm(d_model)
        self.dropout = dropout_layer(cfg, cfg["dropout"])

        self.classifier = nn.Sequential(
            nn.Linear(d_model, d_model * 4),
            norm_layer(cfg, d_model * 4),
            nn.GELU(),
            dropout_layer(cfg, cfg["dropout"]),
            nn.Linear(d_model * 4, d_model * 2),
            norm_layer(cfg, d_model * 2),
            nn.GELU(),
            dropout_layer(cfg, cfg["dropout"]),
            nn.Linear(d_model * 2, d_model),
            norm_layer(cfg, d_model),
            nn.GELU(),
            dropout_layer(cfg, cfg["dropout"]),
            nn.Linear(d_model, n_classes)
        )

        self.boosting_heads = nn.ModuleList()

    def add_boosting_head(self):
        cfg = self.cfg
        d_model = self.d_model
        head = nn.Sequential(
            nn.Linear(d_model, d_model * 2),
            norm_layer(cfg, d_model * 2),
            nn.GELU(),
            dropout_layer(cfg, cfg["boosting_dropout"]),
            nn.Linear(d_model * 2, d_model),
            norm_layer(cfg, d_model),
            nn.GELU(),
            dropout_layer(cfg, cfg["boosting_dropout"]),
            nn.Linear(d_model, self.n_classes)
        )
        self.boosting_heads.append(head)
        return head

    def forward(self, x, use_boosting=False):
        batch_size, n_feat = x.shape
        x = x.unsqueeze(-1)
        x = self.feature_embedding(x)
        x = x + self.pos_scale * self.pos_embedding[:, :n_feat, :]
        x = self.dropout(x)
        x = self.transformer(x)
        x = self.layer_norm(x)
        x = x.mean(dim=1)

        logits = self.classifier(x)

        if use_boosting and len(self.boosting_heads) > 0:
            for head in self.boosting_heads:
                logits = logits + head(x)

        return logits


def distillation_loss(student_logits, teacher_logits, labels, temperature, alpha):
    soft_targets = F.softmax(teacher_logits / temperature, dim=1)
    soft_loss = F.kl_div(
        F.log_softmax(student_logits / temperature, dim=1),
        soft_targets,
        reduction='batchmean'
    ) * (temperature ** 2)
    hard_loss = F.cross_entropy(student_logits, labels)
    return alpha * soft_loss + (1 - alpha) * hard_loss


def train_task(cfg, model, train_loader, val_loader, teacher_model=None, epochs=25, task_name="Task"):
    use_distill = cfg["use_distillation"] and teacher_model is not None
    if use_distill:
        teacher_model.to(DEVICE)
        teacher_model.eval()

    optimizer = torch.optim.AdamW(model.parameters(), lr=cfg["lr"], weight_decay=cfg["weight_decay"])
    scheduler = None
    if cfg["use_lr_schedule"]:
        scheduler = torch.optim.lr_scheduler.CosineAnnealingWarmRestarts(optimizer, T_0=20, T_mult=2)

    best_val_acc = 0.0
    best_state = None
    patience_counter = 0

    for epoch in range(1, epochs + 1):
        model.train()
        for xb, yb in tqdm(train_loader, desc=f"{task_name} Ep {epoch}/{epochs}", leave=False):
            xb, yb = xb.to(DEVICE), yb.to(DEVICE)

            optimizer.zero_grad()
            logits = model(xb, use_boosting=cfg["use_boosting_heads"])

            if use_distill:
                with torch.no_grad():
                    teacher_logits = teacher_model(xb, use_boosting=cfg["use_boosting_heads"])
                loss = distillation_loss(logits, teacher_logits, yb, cfg["temperature"], cfg["distillation_alpha"])
            else:
                loss = F.cross_entropy(logits, yb)

            loss.backward()
            if cfg["use_grad_clip"]:
                torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
            optimizer.step()

        model.eval()
        val_preds, val_labels = [], []
        with torch.no_grad():
            for xb, yb in val_loader:
                xb, yb = xb.to(DEVICE), yb.to(DEVICE)
                logits = model(xb, use_boosting=cfg["use_boosting_heads"])
                val_preds.extend(logits.argmax(dim=1).cpu().numpy())
                val_labels.extend(yb.cpu().numpy())

        val_acc = accuracy_score(val_labels, val_preds)

        if scheduler is not None:
            scheduler.step()

        if val_acc > best_val_acc:
            best_val_acc = val_acc
            best_state = copy.deepcopy(model.state_dict())
            patience_counter = 0
        else:
            patience_counter += 1
            if patience_counter >= PATIENCE:
                break

    model.load_state_dict(best_state)
    return model, best_val_acc


def evaluate_model(cfg, model, loader):
    model.eval()
    all_preds, all_labels = [], []
    with torch.no_grad():
        for xb, yb in loader:
            xb, yb = xb.to(DEVICE), yb.to(DEVICE)
            logits = model(xb, use_boosting=cfg["use_boosting_heads"])
            all_preds.extend(logits.argmax(dim=1).cpu().numpy())
            all_labels.extend(yb.cpu().numpy())

    return {
        "accuracy": accuracy_score(all_labels, all_preds),
        "precision": precision_score(all_labels, all_preds, average='weighted', zero_division=0),
        "recall": recall_score(all_labels, all_preds, average='weighted', zero_division=0),
        "f1_score": f1_score(all_labels, all_preds, average='weighted', zero_division=0),
    }


def run_continual_experiment(cfg):
    """Runs the full 3-task continual learning sequence for one config."""
    set_seed(SEED)
    model = ConfigurableFBCLTransformer(cfg, n_features, n_classes).to(DEVICE)

    all_models = []
    for task_idx, task_name in enumerate(TASK_NAMES):
        if task_idx > 0 and cfg["use_boosting_heads"]:
            new_head = model.add_boosting_head()
            new_head.to(DEVICE)

        teacher = all_models[-1] if all_models else None
        train_loader = make_train_loader(cfg)

        model, val_acc = train_task(
            cfg, model, train_loader, val_loader,
            teacher_model=teacher,
            epochs=EPOCHS_PER_TASK,
            task_name=f"{cfg['name']}:{task_name}"
        )
        all_models.append(copy.deepcopy(model))

    metrics = evaluate_model(cfg, model, test_loader)
    metrics["variant"] = cfg["name"]
    metrics["params"] = sum(p.numel() for p in model.parameters())
    return metrics


