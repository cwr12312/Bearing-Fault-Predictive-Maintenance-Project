class OptimizedmamlTransformer(nn.Module):
    def __init__(self, cfg, n_features, n_classes):
        super().__init__()
        self.cfg = cfg
        self.n_features = n_features
        self.d_model = cfg["d_model"]
        self.n_classes = n_classes

        self.feature_embedding = nn.Linear(1, self.d_model)
        self.mask_token = nn.Parameter(torch.randn(1, 1, self.d_model) * 0.02)
        self.cls_token = nn.Parameter(torch.randn(1, 1, self.d_model) * 0.02)
        self.pos_embedding = nn.Parameter(torch.randn(1, n_features + 1, self.d_model) * 0.02)

        encoder_layer = nn.TransformerEncoderLayer(
            d_model=self.d_model,
            nhead=cfg["n_heads"],
            dim_feedforward=self.d_model * 8,
            dropout=cfg["dropout"],
            batch_first=True,
            activation='gelu',
            norm_first=True
        )
        self.transformer = nn.TransformerEncoder(encoder_layer, num_layers=cfg["n_layers"])
        self.layer_norm = nn.LayerNorm(self.d_model)
        self.dropout = nn.Dropout(cfg["dropout"])

        self.reconstruction_head = nn.Sequential(
            nn.Linear(self.d_model, self.d_model),
            nn.GELU(),
            nn.Dropout(cfg["dropout"]),
            nn.Linear(self.d_model, 1)
        )

        self.classification_head = nn.Sequential(
            nn.Linear(self.d_model, self.d_model * 4),
            nn.BatchNorm1d(self.d_model * 4),
            nn.GELU(),
            nn.Dropout(cfg["dropout"]),
            nn.Linear(self.d_model * 4, self.d_model * 2),
            nn.BatchNorm1d(self.d_model * 2),
            nn.GELU(),
            nn.Dropout(cfg["dropout"]),
            nn.Linear(self.d_model * 2, self.d_model),
            nn.BatchNorm1d(self.d_model),
            nn.GELU(),
            nn.Dropout(cfg["dropout"]),
            nn.Linear(self.d_model, n_classes)
        )

        self.pretraining_mode = True

    def forward(self, x, mask=None):
        batch_size, n_feat = x.shape
        x = x.unsqueeze(-1)
        x = self.feature_embedding(x)
        if mask is not None:
            mask_expanded = mask.unsqueeze(-1).expand(-1, -1, self.d_model)
            mask_token_expanded = self.mask_token.expand(batch_size, n_feat, self.d_model)
            x = torch.where(mask_expanded, mask_token_expanded, x)

        cls_tokens = self.cls_token.expand(batch_size, -1, -1)
        x = torch.cat([cls_tokens, x], dim=1)
        x = x + self.pos_embedding[:, :x.size(1), :]
        x = self.dropout(x)
        x = self.transformer(x)
        x = self.layer_norm(x)

        if self.pretraining_mode:
            reconstructions = self.reconstruction_head(x[:, 1:, :])
            return reconstructions.squeeze(-1)
        else:
            cls_representation = x[:, 0]
            logits = self.classification_head(cls_representation)
            return logits

    def switch_to_finetune(self):
        self.pretraining_mode = False

