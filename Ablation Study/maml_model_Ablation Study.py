# 6. Run a Single Experiment (pretrain + finetune + eval)
# ============================================================
def run_experiment(cfg):
    set_seed(SEED)  # reset seed for reproducibility
    model = OptimizedmamlTransformer(cfg, n_features, n_classes).to(DEVICE)

    # Create pretrain loader if pretraining is enabled
    if cfg["use_pretraining"]:
        pretrain_dataset = MAMLDataset(X_train_t, cfg, pretrain=True)
        pretrain_loader = DataLoader(pretrain_dataset, batch_size=cfg["batch_size"], shuffle=True, num_workers=0)
    else:
        pretrain_loader = None
        print("Skipping pretraining (use_pretraining=False)")

    # Main loaders
    train_loader, val_loader, test_loader = make_loaders(cfg)

    # Pretraining
    if cfg["use_pretraining"] and pretrain_loader is not None:
        pretrain_losses = pretrain_maml(model, cfg, pretrain_loader, cfg["epochs_pretrain"])
    else:
        pretrain_losses = []

    # Fine-tuning
    model, best_val_acc, train_accs, val_accs, train_losses, val_losses = finetune_maml(
        model, cfg, train_loader, val_loader, cfg["epochs_finetune"]
    )

    # Evaluation with TTA
    test_metrics = evaluate_model(model, cfg, test_loader)

    # Return metrics and histories for possible plotting
    return {
        "variant": cfg["name"],
        "accuracy": test_metrics["accuracy"],
        "precision": test_metrics["precision"],
        "recall": test_metrics["recall"],
        "f1": test_metrics["f1"],
        "params": sum(p.numel() for p in model.parameters()),
        "best_val_acc": best_val_acc,
        "pretrain_losses": pretrain_losses,
        "train_losses": train_losses,
        "val_losses": val_losses,
        "train_accs": train_accs,
        "val_accs": val_accs,
    }

