def random_masking(x, cfg):
    mask_ratio = cfg["mask_ratio"]
    batch_size, n_feat = x.shape
    mask = torch.zeros_like(x, dtype=torch.bool)
    num_mask = max(1, int(n_feat * mask_ratio))
    masked_x = x.clone()
    for i in range(batch_size):
        indices = torch.randperm(n_feat)[:num_mask]
        for idx in indices:
            r = torch.rand(1).item()
            if r < cfg["replace_with_mask"]:
                masked_x[i, idx] = 0.0
                mask[i, idx] = True
            elif r < cfg["replace_with_mask"] + cfg["replace_with_random"]:
                random_idx = torch.randint(0, batch_size, (1,)).item()
                masked_x[i, idx] = x[random_idx, idx]
                mask[i, idx] = True
            else:
                mask[i, idx] = False
    return masked_x, mask

class MAMLDataset(torch.utils.data.Dataset):
    def __init__(self, X, cfg, pretrain=True):
        self.X = X
        self.cfg = cfg
        self.pretrain = pretrain
    def __len__(self):
        return len(self.X)
    def __getitem__(self, idx):
        x = self.X[idx]
        if self.pretrain:
            x_batch = x.unsqueeze(0)
            masked_x, mask = random_masking(x_batch, self.cfg)
            return masked_x.squeeze(0), mask.squeeze(0), x
        else:
            return x, self.y[idx] if hasattr(self, 'y') else x

