def pretrain_maml(model, cfg, train_loader, epochs):
    print("\n" + "="*70)
    print("PRETRAINING")
    print("="*70)

    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=cfg["lr_pretrain"],
        weight_decay=cfg["weight_decay"],
        betas=(0.9, 0.98)
    )
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=epochs)
    model.train()
    model.pretraining_mode = True
    losses = []

    for epoch in range(1, epochs + 1):
        total_loss = 0.0
        num_batches = 0
        progress_bar = tqdm(train_loader, desc=f"Pretrain Epoch {epoch}/{epochs}", leave=False)
        for masked_x, mask, original_x in progress_bar:
            masked_x, mask, original_x = masked_x.to(DEVICE), mask.to(DEVICE), original_x.to(DEVICE)
            optimizer.zero_grad()
            reconstructions = model(masked_x, mask)
            mask_float = mask.float()
            recon_loss = F.mse_loss(reconstructions, original_x, reduction='none')
            recon_loss = (recon_loss * mask_float).sum() / (mask_float.sum() + 1e-8)
            recon_loss.backward()
            if cfg["use_gradient_clipping"]:
                torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=cfg["gradient_clip_norm"])
            optimizer.step()
            total_loss += recon_loss.item()
            num_batches += 1
            progress_bar.set_postfix({'loss': f"{recon_loss.item():.6f}"})

        avg_loss = total_loss / num_batches
        losses.append(avg_loss)
        scheduler.step()
        if epoch % 10 == 0 or epoch == epochs:
            print(f"Epoch {epoch}/{epochs}, Loss: {avg_loss:.6f}")
    return losses

def finetune_maml(model, cfg, train_loader, val_loader, epochs):
    print("\n" + "="*70)
    print("FINE-TUNING")
    print("="*70)

    model.switch_to_finetune()

    # Compute class weights for fine-tuning loss
    y_train_all = []
    for _, labels in train_loader:
        y_train_all.extend(labels.numpy())
    class_weights = compute_class_weight('balanced', classes=np.unique(y_train_all), y=y_train_all)
    class_weights = torch.tensor(class_weights, dtype=torch.float32).to(DEVICE)

    # Cross-entropy with optional label smoothing
    if cfg["use_label_smoothing"]:
        criterion = nn.CrossEntropyLoss(weight=class_weights, label_smoothing=cfg["label_smoothing"])
    else:
        criterion = nn.CrossEntropyLoss(weight=class_weights)

    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=cfg["lr_finetune"],
        weight_decay=cfg["weight_decay"],
        betas=(0.9, 0.98)
    )
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=epochs)

    best_val_acc = 0.0
    best_state = None
    patience_counter = 0
    train_accs, val_accs, train_losses, val_losses = [], [], [], []

    for epoch in range(1, epochs + 1):
        model.train()
        train_preds, train_labels = [], []
        train_loss = 0.0

        for xb, yb in tqdm(train_loader, desc=f"Fine-tune Epoch {epoch}/{epochs}", leave=False):
            xb, yb = xb.to(DEVICE), yb.to(DEVICE)
            # Optional input noise
            noise = torch.randn_like(xb) * cfg["finetune_noise_std"]
            xb = xb + noise
            optimizer.zero_grad()
            logits = model(xb, mask=None)
            loss = criterion(logits, yb)
            loss.backward()
            if cfg["use_gradient_clipping"]:
                torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=cfg["gradient_clip_norm"])
            optimizer.step()
            train_loss += loss.item()
            train_preds.extend(logits.argmax(dim=1).cpu().numpy())
            train_labels.extend(yb.cpu().numpy())

        train_acc = accuracy_score(train_labels, train_preds)
        train_accs.append(train_acc)
        train_losses.append(train_loss / len(train_loader))

        model.eval()
        val_preds, val_labels = [], []
        val_loss = 0.0
        with torch.no_grad():
            for xb, yb in val_loader:
                xb, yb = xb.to(DEVICE), yb.to(DEVICE)
                logits = model(xb, mask=None)
                loss = criterion(logits, yb)
                val_loss += loss.item()
                val_preds.extend(logits.argmax(dim=1).cpu().numpy())
                val_labels.extend(yb.cpu().numpy())
        val_acc = accuracy_score(val_labels, val_preds)
        val_accs.append(val_acc)
        val_losses.append(val_loss / len(val_loader))

        scheduler.step()
        print(f"Epoch {epoch}/{epochs} | Train Acc: {train_acc:.4f} | Val Acc: {val_acc:.4f}")

        if val_acc > best_val_acc:
            best_val_acc = val_acc
            best_state = copy.deepcopy(model.state_dict())
            patience_counter = 0
        else:
            patience_counter += 1
            if patience_counter >= cfg["patience"]:
                print(f"Early stopping at epoch {epoch}")
                break

    model.load_state_dict(best_state)
    return model, best_val_acc, train_accs, val_accs, train_losses, val_losses

def evaluate_model(model, cfg, loader):
    model.eval()
    all_preds, all_labels = [], []
    with torch.no_grad():
        for xb, yb in tqdm(loader, desc="Evaluating", leave=False):
            xb = xb.to(DEVICE)
            if cfg["use_dropout_ensemble"]:
                all_probs = []
                for _ in range(cfg["num_passes"]):
                    model.train()
                    logits = model(xb, mask=None)
                    probs = F.softmax(logits, dim=1)
                    all_probs.append(probs.cpu().numpy())
                    model.eval()
                avg_probs = np.mean(all_probs, axis=0)
                preds = np.argmax(avg_probs, axis=1)
            else:
                logits = model(xb, mask=None)
                preds = logits.argmax(dim=1).cpu().numpy()
            all_preds.extend(preds)
            all_labels.extend(yb.numpy())
    accuracy = accuracy_score(all_labels, all_preds)
    precision = precision_score(all_labels, all_preds, average='weighted', zero_division=0)
    recall = recall_score(all_labels, all_preds, average='weighted', zero_division=0)
    f1 = f1_score(all_labels, all_preds, average='weighted', zero_division=0)
    return {
        'accuracy': accuracy,
        'precision': precision,
        'recall': recall,
        'f1': f1,
        'predictions': all_preds,
        'labels': all_labels
    }

