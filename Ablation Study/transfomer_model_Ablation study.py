# ============================================================
# ABLATION STUDY: TRANSFORMER FOR BEARING FAULT DETECTION
# Variants tested:
#   0. Full model (baseline)
#   1. No Gaussian Noise
#   2. No Label Smoothing
#   3. No L2 Regularization
#   4. Single Transformer Block instead of 3 blocks
#   5. No Dropout
#   6. Four Attention Heads instead of Two
#   7. No Gradient Clipping
#   8. Fixed Higher Learning Rate, No ReduceLROnPlateau
#   9. No Dense Classification Head after Global Average Pooling
#  10. With Class Weights for Imbalanced Classes
