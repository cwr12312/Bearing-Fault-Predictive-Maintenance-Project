# 4. TRAINING FUNCTION (takes config dict)
# ============================================================
def run_experiment(cfg):
    set_seed(SEED)   # reset seed for each run

    # Model
    model = FaultTransformer(
        n_feat=n_feat,
        n_classes=n_classes,
        d_model=cfg['d_model'],
        n_heads=cfg['n_heads'],
        n_layers=cfg['n_layers'],
        dropout=cfg['dropout']
    )
    model.to(DEVICE)

    # Loaders (batch size from config)
    train_loader, val_loader, test_loader = get_loaders(cfg['batch_size'])

    # Loss
    cw = torch.tensor(cw_np, dtype=torch.float32)
    criterion = nn.CrossEntropyLoss(
        weight=cw if cfg['use_weighted_sampler'] else None,
        label_smoothing=cfg['label_smoothing'] if cfg['use_label_smoothing'] else 0.0
    )

    # Optimizer
    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=cfg['lr'],
        weight_decay=cfg['weight_decay']
    )
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(
        optimizer,
        T_max=cfg['epochs'],
        eta_min=cfg['lr_min']
    )

    best_acc = 0.0
    best_state = None
    wait = 0

    for epoch in range(1, cfg['epochs'] + 1):
        # Training
        model.train()
        tp, tl = [], []
        tloss = 0.0
        pbar = tqdm(train_loader, total=len(train_loader),
                    desc=f"Epoch {epoch}/{cfg['epochs']}", leave=False)
        for xb, yb in pbar:
            optimizer.zero_grad(set_to_none=True)
            out = model(xb)
            loss = criterion(out, yb)
            loss.backward()
            if cfg['use_grad_clip']:
                torch.nn.utils.clip_grad_norm_(model.parameters(), cfg['grad_clip'])
            optimizer.step()
            tloss += loss.item()
            tp.extend(out.argmax(1).detach().numpy())
            tl.extend(yb.numpy())
            pbar.set_postfix(loss=f"{loss.item():.6f}")
        scheduler.step()

        # Validation
        model.eval()
        vp, vl = [], []
        vloss = 0.0
        with torch.no_grad():
            for xb, yb in val_loader:
                out = model(xb)
                loss = criterion(out, yb)
                vloss += loss.item()
                vp.extend(out.argmax(1).numpy())
                vl.extend(yb.numpy())
        va_acc = accuracy_score(vl, vp)

        if va_acc > best_acc:
            best_acc = va_acc
            best_state = copy.deepcopy(model.state_dict())
            wait = 0
        else:
            wait += 1
            if wait >= cfg['patience']:
                break

    model.load_state_dict(best_state)

    # Evaluation on test set
    model.eval()
    test_preds, test_labels = [], []
    with torch.no_grad():
        for xb, yb in test_loader:
            out = model(xb)
            test_preds.extend(out.argmax(1).numpy())
            test_labels.extend(yb.numpy())

    test_acc = accuracy_score(test_labels, test_preds)
    test_prec = precision_score(test_labels, test_preds, average='weighted', zero_division=0)
    test_rec = recall_score(test_labels, test_preds, average='weighted', zero_division=0)
    test_f1 = f1_score(test_labels, test_preds, average='weighted', zero_division=0)

    n_params = sum(p.numel() for p in model.parameters() if p.requires_grad)

    return {
        'variant': cfg['name'],
        'test_acc': test_acc,
        'test_prec': test_prec,
        'test_rec': test_rec,
        'test_f1': test_f1,
        'best_val_acc': best_acc,
        'params': n_params,
    }

